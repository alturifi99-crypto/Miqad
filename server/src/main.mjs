import {createApp} from './app.mjs';
import {createSetupApp} from './setup-app.mjs';
import {probeDatabase} from './database-probe.mjs';
import {inspectDatabase} from './database-readiness.mjs';
import {initializeDatabase} from './initialize-database.mjs';
const mode=process.env.DEPLOYMENT_MODE||'application';
if(!['setup','application'].includes(mode))throw Error('Invalid deployment mode');
let app;
if(mode==='setup'){const database=await probeDatabase();const preparation=database.status==='connected'?await initializeDatabase():{status:'not_requested'};const readiness=!['not_requested','initialized'].includes(preparation.status)?preparation:database.status==='connected'?await inspectDatabase():{status:'not_checked'};if(preparation.status==='initialized'&&readiness.status==='schema_checks_passed')readiness.status='schema_verified';app=createSetupApp({database,readiness});}else app=await createApp();
const port=Number(process.env.PORT||8090);
if(!Number.isInteger(port)||port<1||port>65535)throw Error('Invalid listening port');
await app.listen({host:process.env.RENDER==='true'?'0.0.0.0':'127.0.0.1',port});
console.log(mode==='setup'?'Miqad hosting setup is online. Company APIs are disabled.':'Miqad development application is online. Production rollout is disabled.');
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{await app.close();process.exit(0);});
